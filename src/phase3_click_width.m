function Q = phase3_click_width(fs, width_us, errid)
%PHASE3_CLICK_WIDTH Require an exact sample count for the protocol click.
if nargin < 3 || isempty(errid), errid = 'phase3_click_width:unrepresentable'; end
if ~isnumeric(fs) || ~isscalar(fs) || ~isreal(fs) || ~isfinite(fs) || fs <= 0 || ...
        ~isnumeric(width_us) || ~isscalar(width_us) || ~isreal(width_us) || ...
        ~isfinite(width_us) || width_us <= 0
    error(errid, 'fs と width_us は正の有限実数スカラである必要があります。');
end
protocol_us = phase3_protocol_const().click_width_us;
protocol_tol_us = max(1e-9, 16*eps(max(abs([protocol_us width_us]))));
if abs(width_us-protocol_us) > protocol_tol_us
    error(errid, ...
        ['Phase 3 のクリック幅は 5/48000 秒 = %.12g us に固定です ' ...
         '(指定: %.12g us)。クリック列の刺激条件を確認してください。'], ...
        protocol_us, width_us);
end
n = round(width_us*1e-6*fs);
actual_us = n/fs*1e6;
tol_us = max(1e-9, 16*eps(max(abs([width_us actual_us]))));
if n < 1 || abs(actual_us-width_us) > tol_us
    error(errid, ...
        ['クリック幅 %.12g us は fs=%g Hz で正確に表現できません ' ...
         '(最も近い幅: %d samples = %.12g us)。48/96/192 kHz など、' ...
         '48 kHz の整数倍を使用してください。'], ...
        width_us, fs, n, actual_us);
end
Q = struct('samples',n,'requested_us',width_us,'actual_us',actual_us);
end
