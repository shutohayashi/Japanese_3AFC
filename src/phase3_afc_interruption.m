function yes=phase3_afc_interruption(identifier)
%PHASE3_AFC_INTERRUPTION Expected stops, never arbitrary configuration/code errors.
yes=ismember(identifier,{'phase3_afc_threshold:aborted', ...
    'phase3_afc_threshold:uiclosed','phase3_afc_threshold:underrun', ...
    'phase3_afc_threshold:primingunderrun','phase3_afc_threshold:cuelate', ...
    'phase3_afc_threshold:streamtimeout','phase3_afc_threshold:queuefailure', ...
    'phase3_afc_threshold:streamincomplete'});
end
